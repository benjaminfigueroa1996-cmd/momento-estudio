-- Cotización automática: cada solicitud guarda su cálculo y un enlace privado
alter table quote_requests
  add column if not exists number bigint generated by default as identity,
  add column if not exists token text unique,
  add column if not exists package text,
  add column if not exists options jsonb not null default '{}'::jsonb,
  add column if not exists quote jsonb,
  add column if not exists total int,
  add column if not exists valid_until date,
  add column if not exists needs_review boolean not null default false;
create index if not exists quote_requests_token_idx on quote_requests (token);
